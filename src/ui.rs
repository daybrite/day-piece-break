//! The ready-made consent surface (feature `ui`): a banner an app embeds to disclose a pending
//! crash report and let the user view, send, or discard it. Everything the user reads is localized
//! (en/fr/ar/zh-CN, the crate's private catalog in `resource/locales/`, named through the
//! generated `res::str`); the destination disclosure comes from the configured
//! [`Reporter`]'s `describe`. Nothing is uploaded until the user taps Send.

use day_pieces::prelude::*;

use crate::ReportMeta;

// The consent surface's private Fluent catalog (resource/locales/<lang>/app.ftl), generated by
// build.rs: `res::str::crash_title()` and its siblings.
day_fluent::locales!();

/// Theme-neutral card surface (translucent mid-gray reads on both light and dark themes, so the
/// default label colors stay legible; the showcase idiom, see day-ui-visual-checks).
const CARD: Color = Color::rgba(0.5, 0.5, 0.55, 0.16);

fn card(content: AnyPiece) -> AnyPiece {
    content
        .padding(14.0)
        .background(CARD)
        .corner_radius(12.0)
        .any()
}

/// A banner disclosing the newest pending crash report, with View / Send / Discard. Renders
/// nothing when there is no pending report. Embed it near the top of a screen; it is reactive,
/// so it appears when a crash is pending and disappears once the user sends or discards it.
pub fn consent_banner() -> AnyPiece {
    let pending = crate::pending();
    let expanded = Signal::new(false);
    let status = Signal::new(String::new());
    when(
        move || !pending.get().is_empty(),
        move || banner_body(pending, expanded, status),
    )
    .any()
}

fn banner_body(
    pending: Signal<Vec<ReportMeta>>,
    expanded: Signal<bool>,
    status: Signal<String>,
) -> AnyPiece {
    // The newest pending report drives the banner.
    let Some(meta) = pending.get().into_iter().next() else {
        return spacer().any();
    };

    let disclosure = crate::state()
        .and_then(|s| s.reporter.as_ref().map(|r| r.describe()))
        .unwrap_or_default();

    let view_meta = meta.clone();
    let toggle = move || expanded.set(!expanded.get_untracked());

    let send_meta = meta.clone();
    // Localize on the main thread now (formatting reads the live locale signal, which is not
    // valid on the transport's worker thread); the completion callback just picks a precomputed
    // string and writes it through a Setter (the cross-thread-safe signal write).
    let (sending, sent, failed) = (
        res::str::crash_sending().format(),
        res::str::crash_sent().format(),
        res::str::crash_failed().format(),
    );
    let status_setter = status.setter();
    let on_send = move || {
        status.set(sending.clone());
        let (sent, failed) = (sent.clone(), failed.clone());
        crate::send(&send_meta, move |res| {
            status_setter.set(if res.is_ok() { sent } else { failed });
        });
    };

    let discard_meta = meta.clone();
    let on_discard = move || crate::discard(&discard_meta);

    let report_body = move || {
        // Read-only display of the full report; a scrolled label so nothing is editable.
        let text = crate::report_text(&view_meta);
        scroll(label(text).font(Font::Caption)).any()
    };

    card(
        column((
            label(res::str::crash_title())
                .font(Font::Headline)
                .id(day_core::id!(dbreak_title)),
            label(res::str::crash_body()).font(Font::Footnote),
            when(
                move || !status.get().is_empty(),
                move || {
                    label(status.get())
                        .font(Font::Callout)
                        .id(day_core::id!(dbreak_status))
                },
            ),
            when(move || expanded.get(), report_body)
                .any()
                .id(day_core::id!(dbreak_report)),
            row((
                button(res::str::crash_view())
                    .action(toggle)
                    .id(day_core::id!(dbreak_view)),
                button(res::str::crash_send())
                    .action(on_send)
                    .id(day_core::id!(dbreak_send)),
                button(res::str::crash_discard())
                    .action(on_discard)
                    .id(day_core::id!(dbreak_discard)),
            ))
            .spacing(8.0),
            when(
                {
                    let has = !disclosure.is_empty();
                    move || has
                },
                move || label(disclosure.clone()).font(Font::Caption2),
            ),
        ))
        .spacing(8.0)
        .any(),
    )
    .id(day_core::id!(dbreak_banner))
    .any()
}

#[cfg(test)]
mod tests {
    /// English is the source of keys, and every other catalog defines the same set, so no locale
    /// falls back to English partway through the banner.
    #[test]
    fn every_locale_defines_every_key() {
        let keys = |src: &str| -> Vec<String> {
            src.lines()
                .filter(|l| !l.trim_start().starts_with('#') && l.contains('='))
                .filter_map(|l| l.split('=').next().map(|k| k.trim().to_string()))
                .filter(|k| !k.is_empty())
                .collect()
        };
        let en = keys(include_str!("../resource/locales/en/app.ftl"));
        assert!(!en.is_empty());
        for (loc, src) in [
            ("fr", include_str!("../resource/locales/fr/app.ftl")),
            ("ar", include_str!("../resource/locales/ar/app.ftl")),
            ("zh-CN", include_str!("../resource/locales/zh-CN/app.ftl")),
        ] {
            let ks = keys(src);
            for k in &en {
                assert!(ks.contains(k), "locale {loc} is missing key `{k}`");
            }
        }
    }
}
